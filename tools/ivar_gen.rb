# ivar_gen.rb -- generate the boxes of the ivars of the objects of a kernel.
#
# Usage: ruby tools/ivar_gen.rb KERNEL.c > ivars.c
#
# spinel writes a table for the default inspect into the kernel
# (sp_insp_tab): a row for each class, with the name, the field offset, the
# nil byte and the kind of each ivar. Each kind has a function that renders
# a field of the kind (sp_insp_fn_N). This tool writes, for each kind, a
# function that boxes such a field instead:
#
#   static sp_RbVal fx_iv_box_N(void *s, const uint8_t *nb);
#
# A scalar kind renders through sp_poly_inspect(BOX), so its box is BOX. A
# container kind renders through its typed inspect, so its box comes from the
# C type of the field (tools/c_box.rb). A kind with no box gets a function
# that raises NotImplementedError. With no table in the kernel, the output defines
# nothing, and Fluxpinel builds without the ivars of the kernel. The output
# goes into the TU of the host build after entries.c (docs/design.md,
# section 5.1).

require_relative "c_box"

kernel = ARGV[0]
abort "usage: ruby tools/ivar_gen.rb KERNEL.c" if kernel.nil?
src = File.read(kernel)

out = +"/* Generated by tools/ivar_gen.rb from #{File.basename(kernel)}. Do not edit. */\n\n"
ninsp = src[/\bsp_insp_tab\[(\d+)\]/, 1]
unless ninsp
  print out
  exit
end

kinds = {}
src.scan(/^static const char \*sp_insp_fn_(\d+)\(void \*s, const uint8_t \*nb\) \{ \(void\)s; \(void\)nb; return (.*); \}$/) do |k, body|
  kinds[k.to_i] = body
end

out << "#define FX_KERNEL_IVARS 1\n#define FX_KERNEL_NINSP #{ninsp}\n\n"
n = kinds.empty? ? 0 : kinds.keys.max + 1
n.times do |k|
  body = kinds[k]
  box =
    if body.nil? then nil
    elsif body =~ /\Asp_poly_inspect\((.*)\)\z/ then $1
    elsif body =~ /\(\*\(([\w ]+ \*) \*\)s\)/ then CBox.box($1, "(*(#{$1} *)s)")
    end
  box ||= %{(sp_raise_cls("NotImplementedError", "fluxpinel: no box for an ivar of the kernel of kind #{k}"), sp_box_nil())}
  out << "static sp_RbVal fx_iv_box_#{k}(void *s, const uint8_t *nb) { (void)s; (void)nb; return #{box}; }\n"
end
out << "\nstatic sp_RbVal (*const fx_iv_box[])(void *, const uint8_t *) = {"
out << (n.zero? ? " NULL" : (0...n).map { |k| " fx_iv_box_#{k}" }.join(","))
out << " };\n"
print out
