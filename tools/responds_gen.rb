# responds_gen.rb -- write the public methods of the builtin classes of
# CRuby, for respond_to? on a builtin value (src/responds.c).
#
# Usage: ruby --disable-gems tools/responds_gen.rb src/fx_tu.c > build/responds.inc
#
# The classes are the builtin classes of spinel (fx_builtin_class_names of
# src/fx_tu.c), each class and module at the top level of CRuby, the
# nested classes in EXTRA, and each ancestor of them. A row
# gives the own public instance methods of a class, the own public methods
# of its singleton class, its superclass and its ancestors. src/responds.c
# walks the ancestors, so a method is in the row of its owner only.

EXTRA = %w[MatchData Set Thread Thread::Queue Thread::SizedQueue Thread::Mutex
           Thread::ConditionVariable Fiber Encoding Dir Method UnboundMethod
           Process GC ObjectSpace Random Binding File::Stat Enumerator::Lazy
           Enumerator::Yielder Marshal].freeze

src = File.read(ARGV[0] || abort("usage: ruby tools/responds_gen.rb src/fx_tu.c"))
list = src[/fx_builtin_class_names\[\] = \{(.*?)\};/m, 1] or abort "responds_gen.rb: no fx_builtin_class_names"
names = list.scan(/"([^"]+)"/).flatten + Object.constants.map(&:to_s) + EXTRA

mods = names.filter_map { |n| Object.const_get(n) rescue nil }.grep(Module)
mods = mods.flat_map(&:ancestors).uniq.select(&:name).sort_by(&:name)

def c_str(s) = "\"#{s.to_s.gsub(/[\\"]/) { "\\#{_1}" }}\""

def c_list(name, syms)
  items = syms.map(&:to_s).sort.map { c_str(_1) } + ["NULL"]
  "static const char *const #{name}[] = { #{items.join(', ')} };"
end

puts "/* generated by tools/responds_gen.rb from #{RUBY_DESCRIPTION}: do not edit */"
rows = mods.each_with_index.map do |m, i|
  puts c_list("fx_rs_i#{i}", m.public_instance_methods(false))
  puts c_list("fx_rs_s#{i}", m.singleton_class.public_instance_methods(false))
  puts c_list("fx_rs_a#{i}", m.ancestors.drop(1).filter_map(&:name))
  sup = m.is_a?(Class) && m.superclass&.name
  "  { #{c_str(m.name)}, #{m.is_a?(Class) ? 0 : 1}, #{sup ? c_str(sup) : 'NULL'}, fx_rs_i#{i}, fx_rs_s#{i}, fx_rs_a#{i} },"
end
puts "static const FxRespondRow fx_rs_rows[] = {"
puts rows
puts "};"
