# entry_gen.rb -- generate the wrappers of the entries of a kernel.
#
# Usage: ruby tools/entry_gen.rb ENTRIES KERNEL.h > entries.c
#
# ENTRIES is the list of --ext-entry (Mod.m,...). KERNEL.h is the header
# that spinel writes beside the kernel. Each entry becomes a wrapper
#
#   static sp_RbVal fx_entry_N(sp_RbVal *argv);
#
# that converts each argument to the C type of its parameter, calls the
# entry and boxes the result. The table fx_kernel_entries[] names them.
# The output goes into the TU of the host build after the kernel
# (docs/design.md, section 3.6).

entries, header = ARGV
abort "usage: ruby tools/entry_gen.rb ENTRIES KERNEL.h" if entries.nil? || header.nil?

# The C name of a method, as mc() of spinel (src/codegen_util.c) makes it.
MC = { "?" => "_p", "!" => "_bang", "=" => "_set", "+" => "_plus", "-" => "_minus", "*" => "_star",
       "/" => "_slash", "%" => "_pct", "<" => "_lt", ">" => "_gt", "&" => "_amp", "|" => "_bar",
       "^" => "_caret", "~" => "_tilde", "@" => "_at", "[" => "_lb", "]" => "_rb" }.freeze

def mc(name)
  s = name.chars.map { |ch| ch.match?(/\w/) ? ch : MC.fetch(ch, "_") }.join
  s == "new" ? "new__m" : s
end

# The prototypes of the header: name => [result type, [parameter types]]
protos = {}
File.foreach(header) do |line|
  next unless line =~ /\A(.+?)\s*\b(sp_\w+)\((.*)\);\s*\z/
  ret, name, params = $1.strip, $2, $3.strip
  types = params.empty? || params == "void" ? [] : params.split(",").map { |p| p.strip.sub(/\s*\b\w+\z/, "") }
  protos[name] = [ret, types]
end

ARG = { "sp_RbVal" => "%s", "sp_int" => "sp_poly_arg_int_chk(%s)", "sp_float" => "sp_poly_to_f(%s)",
        "sp_bool" => "sp_poly_truthy(%s)", "const char *" => "sp_poly_arg_str_chk(%s)",
        "sp_sym" => "fx_entry_sym(%s)" }.freeze

RET = { "sp_RbVal" => "%s", "sp_int" => "sp_box_int(%s)", "sp_float" => "sp_box_float(%s)",
        "sp_bool" => "sp_box_bool(%s)", "sp_sym" => "sp_box_sym(%s)", "const char *" => "fx_entry_str(%s)",
        "sp_PolyArray *" => "sp_box_poly_array(%s)", "sp_IntArray *" => "sp_box_int_array(%s)",
        "sp_FloatArray *" => "sp_box_float_array(%s)", "sp_StrArray *" => "sp_box_str_array(%s)" }.freeze

out = +<<~C
  /* Generated by tools/entry_gen.rb from #{File.basename(header)}. Do not edit. */

  /* a Symbol argument */
  static sp_sym fx_entry_sym(sp_RbVal v) {
    if (v.tag != SP_TAG_SYM) sp_raise_cls("TypeError", sp_sprintf("%s is not a symbol", sp_poly_inspect(v)));
    return (sp_sym)v.v.i;
  }

  /* a String result: NULL is nil */
  static sp_RbVal fx_entry_str(const char *s) { return s ? sp_box_str_new(s) : sp_box_nil(); }

  /* an object of the kernel: it starts with its cls_id */
  static sp_RbVal fx_entry_obj(void *p) { return p ? sp_box_obj(p, *(sp_int *)p) : sp_box_nil(); }

C
rows = []
entries.split(",").each_with_index do |e, i|
  mod, _, meth = e.rpartition(".")
  abort "entry_gen: #{e}: spell an entry Module.method" if mod.empty?
  cname = "sp_#{mod}_s_#{mc(meth)}"
  ret, types = protos.fetch(cname) { abort "entry_gen: #{e}: #{cname} is not in #{header}" }
  args = types.each_with_index.map do |t, j|
    a = "argv[#{j}]"
    if ARG.key?(t) then format(ARG[t], a)
    elsif t.end_with?("*") then "(#{t})#{a}.v.p"
    else abort "entry_gen: #{e}: no conversion to #{t}"
    end
  end
  call = "#{cname}(#{args.join(", ")})"
  body =
    if ret == "void" then "#{call};\n  return sp_box_nil();"
    elsif RET.key?(ret) then "return #{format(RET[ret], call)};"
    elsif ret.end_with?("*") then "return fx_entry_obj(#{call});"
    else abort "entry_gen: #{e}: no box for #{ret}"
    end
  out << "static sp_RbVal fx_entry_#{i}(sp_RbVal *argv) {\n  (void)argv;\n  #{body}\n}\n\n"
  rows << %(  { "#{mod}", "#{meth}", #{types.size}, fx_entry_#{i} },)
end
out << <<~C
  static const struct {
    const char *module, *name;
    int argc;
    sp_RbVal (*fn)(sp_RbVal *argv);
  } fx_kernel_entries[] = {
  #{rows.join("\n")}
  };
  #define FX_NENTRIES ((int)(sizeof fx_kernel_entries / sizeof fx_kernel_entries[0]))
C
print out
