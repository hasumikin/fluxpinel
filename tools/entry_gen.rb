# entry_gen.rb -- generate the wrappers of the entries of a kernel.
#
# Usage: ruby tools/entry_gen.rb ENTRIES KERNEL.h > entries.c
#
# ENTRIES is the list of --ext-entry (Mod.m,...). KERNEL.h is the header
# that spinel writes beside the kernel. Each entry becomes a wrapper
#
#   static sp_RbVal fx_entry_N(sp_RbVal *argv);
#
# that converts each argument to the C type of its parameter, calls the
# entry and boxes the result. The table fx_kernel_entries[] names them.
# The output goes into the TU of the host build after the kernel
# (docs/design.md, section 3.6).
#
# A wrapper checks an argument before the entry reads it: a value of a
# wrong kind raises TypeError. The class id of an object parameter comes
# from KERNEL.c beside the header, where each constructor sets it.

require_relative "c_box"

entries, header = ARGV
abort "usage: ruby tools/entry_gen.rb ENTRIES KERNEL.h" if entries.nil? || header.nil?

# The C name of a method, as mc() of spinel (src/codegen_util.c) makes it.
MC = { "?" => "_p", "!" => "_bang", "=" => "_set", "+" => "_plus", "-" => "_minus", "*" => "_star",
       "/" => "_slash", "%" => "_pct", "<" => "_lt", ">" => "_gt", "&" => "_amp", "|" => "_bar",
       "^" => "_caret", "~" => "_tilde", "@" => "_at", "[" => "_lb", "]" => "_rb" }.freeze

def mc(name)
  s = name.chars.map { |ch| ch.match?(/\w/) ? ch : MC.fetch(ch, "_") }.join
  s == "new" ? "new__m" : s
end

# The prototypes of the header: name => [result type, [parameter types]]
protos = {}
File.foreach(header) do |line|
  next unless line =~ /\A(.+?)\s*\b(sp_\w+)\((.*)\);\s*\z/
  ret, name, params = $1.strip, $2, $3.strip
  types = params.empty? || params == "void" ? [] : params.split(",").map { |p| p.strip.sub(/\s*\b\w+\z/, "") }
  protos[name] = [ret, types]
end

# The class id of each struct of the kernel: a constructor makes `self` of
# the struct and sets its cls_id.
#
#   sp_Shape *self = SP_POOL_NEW(Shape, sp_Shape__gc_scan);
#   ...
#   self->cls_id = 4;
CLS_ID = {}
kernel_c = header.sub(/\.h\z/, ".c")
if File.exist?(kernel_c)
  File.read(kernel_c).scan(/^\s*(sp_\w+) \*self = [^\n]*\n(?:[^\n]*\n){0,3}?\s*self->cls_id = (\d+);/) do |type, id|
    CLS_ID["#{type} *"] ||= id.to_i
  end
end

ARG = { "sp_RbVal" => "%s", "sp_int" => "sp_poly_arg_int_chk(%s)", "sp_float" => "sp_poly_to_f(%s)",
        "sp_bool" => "sp_poly_truthy(%s)", "const char *" => "sp_poly_arg_str_chk(%s)",
        "sp_String *" => "fx_entry_string(%s)",
        "sp_sym" => "fx_entry_sym(%s)", "sp_oint" => "fx_entry_oint_arg(%s)",
        "sp_IntArray *" => "sp_poly_as_int_array(fx_entry_array(%s))",
        "sp_FloatArray *" => "sp_poly_as_float_array(fx_entry_array(%s))",
        "sp_StrArray *" => "sp_poly_as_str_array(fx_entry_array(%s))",
        "sp_PolyArray *" => "sp_poly_to_poly_array(fx_entry_array(%s))",
        "sp_SymPolyHash *" => "sp_poly_as_sym_poly_hash(fx_entry_any_hash(%s))",
        "sp_StrPolyHash *" => "sp_poly_as_str_poly_hash(fx_entry_any_hash(%s))",
        "sp_PolyPolyHash *" => "sp_poly_as_poly_poly_hash(fx_entry_any_hash(%s))" }.freeze

RET = CBox::RET

def hash_id(type) = CBox.hash_id(type)

out = +<<~C
  /* Generated by tools/entry_gen.rb from #{File.basename(header)}. Do not edit. */

  /* a Symbol argument */
  static sp_sym fx_entry_sym(sp_RbVal v) {
    if (v.tag != SP_TAG_SYM) sp_raise_cls("TypeError", sp_sprintf("%s is not a symbol", sp_poly_inspect(v)));
    return (sp_sym)v.v.i;
  }

  /* a String argument. A String has two forms (fx_is_string, src/builtin.c):
     the handle passes as it is, and the literal form, which Symbol#to_s
     answers, gets a handle of its own. nil is no String (NULL), and any
     other value raises TypeError. */
  static sp_String *fx_entry_string(sp_RbVal v) {
    if (v.tag == SP_TAG_NIL) return NULL;
    if (sp_poly_is_strbuf(v)) return (sp_String *)v.v.p;
    return sp_String_new_shared(sp_poly_arg_str_chk(v));
  }

  /* an Array argument. The runtime converts it to the kind of the
     parameter: an Array of that kind passes as it is, and any other one
     passes as a copy, so a change of the entry to it does not reach the
     caller. */
  static sp_RbVal fx_entry_array(sp_RbVal v) {
    if (!(v.tag == SP_TAG_OBJ && sp_poly_is_array_kind(v.cls_id)))
      sp_raise_cls("TypeError", sp_sprintf("no implicit conversion of %s into Array", sp_poly_class_name(v)));
    return v;
  }

  /* a Hash argument whose values are of any kind. The runtime converts it
     to the kind of the parameter, as an Array argument: a Hash of that
     kind passes as it is, and any other one passes as a copy. */
  static sp_RbVal fx_entry_any_hash(sp_RbVal v) {
    if (!(v.tag == SP_TAG_OBJ && sp_poly_is_hash_kind(v.cls_id)))
      sp_raise_cls("TypeError", sp_sprintf("no implicit conversion of %s into Hash", sp_poly_class_name(v)));
    return v;
  }

  /* any other Hash argument: a Hash of the kind of the parameter, as it is */
  static void *fx_entry_hash(sp_RbVal v, sp_int cls_id) {
    if (v.tag != SP_TAG_OBJ || v.cls_id != cls_id)
      sp_raise_cls("TypeError", sp_sprintf("%s does not fit a typed Hash parameter", sp_poly_inspect(v)));
    return v.v.p;
  }

  /* a Hash result: NULL is nil */
  static sp_RbVal fx_entry_hash_box(void *p, sp_int cls_id) { return p ? sp_box_obj(p, cls_id) : sp_box_nil(); }

  /* a String result: NULL is nil */
  static sp_RbVal fx_entry_str(const char *s) { return s ? sp_box_str_new(s) : sp_box_nil(); }

  /* a nullable Integer result: its flag is nil */
  static sp_RbVal fx_entry_oint(sp_oint o) { return o.nil ? sp_box_nil() : sp_box_int(o.v); }

  /* a nullable Integer argument */
  static sp_oint fx_entry_oint_arg(sp_RbVal v) {
    return v.tag == SP_TAG_NIL ? sp_oint_nil() : sp_oint_of(sp_poly_arg_int_chk(v));
  }

  /* an object of the kernel: it starts with its cls_id */
  static sp_RbVal fx_entry_obj(void *p) { return p ? sp_box_obj(p, *(sp_int *)p) : sp_box_nil(); }

C
# The check of an object argument, for a kernel that has an entry with one:
# sp_poly_unbox_cls is a function of the classes of the kernel.
OBJECT_ARG = <<~C
  #include "fx_tu.h"

  /* an object argument: an object of the class of the parameter (cls_id),
     or of a class under it. Any other value raises TypeError. So does nil:
     the header does not say whether the parameter takes nil, and an entry
     that does not would read a NULL object. The kernel knows the ancestry
     of its own classes only (the ids below FX_CLS_BASE), so an object of
     the script or of a builtin class does not reach it. */
  static void *fx_entry_object(sp_RbVal v, int cls_id, const char *want) {
    int of_kernel = v.tag == SP_TAG_OBJ && v.cls_id >= 0 && v.cls_id < FX_CLS_BASE;
    void *p = of_kernel ? sp_poly_unbox_cls(v, cls_id, want) : NULL;
    if (!p) sp_raise_cls("TypeError", sp_sprintf("no implicit conversion of %s into %s", sp_poly_class_name(v), want));
    return p;
  }

C
uses_object = false
wrappers = +""
rows = []
entries.split(",").each_with_index do |e, i|
  mod, _, meth = e.rpartition(".")
  abort "entry_gen: #{e}: spell an entry Module.method" if mod.empty?
  cname = "sp_#{mod}_s_#{mc(meth)}"
  ret, types = protos.fetch(cname) { abort "entry_gen: #{e}: #{cname} is not in #{header}" }
  # Each argument goes into a local first, and a value of the heap (a copy
  # that a conversion made) is a root for the call: the entry may collect
  # before it stores the argument anywhere.
  decls = []
  args = types.each_with_index.map do |t, j|
    a = "argv[#{j}]"
    conv =
      if ARG.key?(t) then format(ARG[t], a)
      elsif hash_id(t) then "(#{t})fx_entry_hash(#{a}, #{hash_id(t)})"
      elsif CLS_ID.key?(t)
        uses_object = true
        %[(#{t})fx_entry_object(#{a}, #{CLS_ID[t]}, "#{t[/\Asp_(\w+)/, 1]}")]
      # a pointer of another kind, as it is
      elsif t.end_with?("*") then "(#{t})#{a}.v.p"
      else abort "entry_gen: #{e}: no conversion to #{t}"
      end
    decls << "#{t}#{t.end_with?("*") ? "" : " "}a#{j} = #{conv};"
    decls << "SP_GC_ROOT_STR(a#{j});" if t == "const char *"
    decls << "SP_GC_ROOT(a#{j});" if t != "const char *" && t.end_with?("*")
    decls << "SP_GC_ROOT_RBVAL(a#{j});" if t == "sp_RbVal"
    "a#{j}"
  end
  call = "#{cname}(#{args.join(", ")})"
  body =
    if ret == "void" then "#{call};\n  return sp_box_nil();"
    elsif RET.key?(ret) then "return #{format(RET[ret], call)};"
    elsif hash_id(ret) then "return fx_entry_hash_box(#{call}, #{hash_id(ret)});"
    elsif ret.end_with?("*") then "return fx_entry_obj(#{call});"
    else abort "entry_gen: #{e}: no box for #{ret}"
    end
  lines = ["(void)argv;", *decls, *body.split("\n")]
  wrappers << "static sp_RbVal fx_entry_#{i}(sp_RbVal *argv) {\n#{lines.map { |l| "  #{l}" }.join("\n")}\n}\n\n"
  rows << %(  { "#{mod}", "#{meth}", #{types.size}, fx_entry_#{i} },)
end
out << OBJECT_ARG if uses_object
out << wrappers
# A kernel with no entry: C has no empty array, so the table keeps one row
# that no code reads.
count = rows.size
rows << "  { NULL, NULL, 0, NULL }," if rows.empty?
out << <<~C
  static const struct {
    const char *module, *name;
    int argc;
    sp_RbVal (*fn)(sp_RbVal *argv);
  } fx_kernel_entries[] = {
  #{rows.join("\n")}
  };
  #define FX_NENTRIES #{count}
C
print out
